-- 2.1 CLIENTES.CPF (nullable: clientes antigos continuam válidos)
ALTER TABLE CLIENTES ADD CPF VARCHAR(11) NULL;
GO

ALTER TABLE CLIENTES
    ADD CONSTRAINT CK_CLIENTES_CPF CHECK (CPF IS NULL OR (LEN(CPF) = 11 AND CPF NOT LIKE '%[^0-9]%'));
GO

CREATE UNIQUE NONCLUSTERED INDEX UX_CLIENTES_CPF
    ON CLIENTES (CPF) WHERE CPF IS NOT NULL;
GO

